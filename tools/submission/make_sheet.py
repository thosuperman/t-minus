#!/usr/bin/env python3
"""Assemble DEVPOST/SUBMISSION_SHEET.md, the copy-paste sheet for the Devpost form, from the source documents.

Usage: python3 tools/submission/make_sheet.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
S = ROOT / 'CODEGEIST-2026-SUBMISSION'
D = S / 'DEVPOST'


def section(text, start, end=None):
    body = text.split(start, 1)[1]
    return (body.split(end, 1)[0] if end else body).strip()


def demote(md, levels=2):
    return re.sub(r'^(#+) ', lambda m: '#' * min(6, len(m.group(1)) + levels) + ' ', md, flags=re.M)


overview = (D / 'Project_Overview.md').read_text().split('\n---\n')[1].strip()
fields = (D / 'Submission_Fields.md').read_text()
tech = (D / 'Technologies.md').read_text()
install = (D / 'Installation_Instructions.md').read_text()
video = (D / 'Video_Description.md').read_text()
link = next(l for l in (ROOT / 'INSTALL_LINK.txt').read_text().splitlines() if l.startswith('http'))
pitch = re.search(r'\*\*Elevator pitch.*?```\n(.+?)\n```', (D / 'Project_Title_and_Tagline.md').read_text(), re.S).group(1)
name = re.search(r'\*\*Project name.*?```\n(.+?)\n```', (D / 'Project_Title_and_Tagline.md').read_text(), re.S).group(1)
built = re.search(r'\| Built with \| (.+?) \|', fields).group(1)
captions = re.findall(r'\| `(0[1-7]_[A-Za-z_]+\.png)` \| [^|]+ \| ([^|]+) \|', (S / 'SCREENSHOTS' / 'README.md').read_text())
rows = '\n'.join(f'| {i} | `SCREENSHOTS/{f}` | {c.strip()} |' for i, (f, c) in enumerate(captions, 1))

out = f"""# Submission sheet

Everything to paste into the Devpost form, in the order the form usually asks for it. Text in code blocks is ready to copy. The Codegeist-specific questions could not be read without a Devpost login, so match section 8 to the form's actual labels.

Generated by `tools/submission/make_sheet.py` from the other files in this folder. Nothing here has been submitted.

## 1. Project name

```
{name}
```

## 2. Elevator pitch ({len(pitch)} of 200 characters)

```
{pitch}
```

## 3. Thumbnail

Upload `SCREENSHOTS/00_Thumbnail.png` (1500 x 1000, 3:2). It is a title card over the real Mission Control screenshot.

## 4. Image gallery

Upload in this order and paste each caption. All are real captures of the installed app, 3200 x 1800 PNG, each under 1 MB.

| # | File | Caption |
|---|---|---|
{rows}

## 5. Video demo link

```
https://youtu.be/Nxrbcvqr1PQ
```

Public on YouTube since 16 November 2026 (3:57). The source file is `VIDEO/Final_Demo_1080p.mp4`.

{demote(section(video, '# Video description'), 2)}

## 6. Built with

```
{built}
```

## 7. Try it out links

```
https://tminus.hayaix.tech
```

```
https://github.com/thosuperman/t-minus
```

## 8. Codegeist questions

**Category**

```
Apps for Specialized Industries
```

**Bonus prize**

```
Best Agents - Rovo/Assignable agents
```

**Installation link**

```
{link}
```

**Why this category**

{section(fields, '### Why this is a Specialized Industries entry', '### Best Agents write-up')}

**How the project meets the technology requirement**

{section(tech, '## How the project meets the technology requirement', '## Forge modules')}

**Best Agents write-up**

{section(fields, '### Best Agents write-up', '## Declarations').replace(' See `REVIEW/Feature_Verification.md`.', '')}

**Testing instructions for judges**

{demote(section(install, 'Time needed: about five minutes.'), 2)}

## 9. About the project

Paste everything between the two lines into "About the project" (Markdown).

---

{overview}

---
"""
(D / 'SUBMISSION_SHEET.md').write_text(out)
print(f'{D / "SUBMISSION_SHEET.md"}: {len(out.split())} words; gallery {len(captions)} images')
